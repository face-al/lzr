package rdp

import "testing"

func TestVerify(t *testing.T) {
	var h HandshakeMod
	tests := []struct {
		name, data, want string
	}{
		{"windows", "\x03\x00\x00\x13\x0e\xd0\xfe\xca\x12\x34\x00\x02\x1f\x08\x00\x02\x00\x00\x00", "rdp"},
		{"xrdp tls", "\x03\x00\x00\x13\x0e\xd0\x00\x00\x12\x34\x00\x02\x01\x08\x00\x01\x00\x00\x00", "rdp"},
		{"xrdp standard security", "\x03\x00\x00\x13\x0e\xd0\x00\x00\x12\x34\x00\x02\x01\x08\x00\x00\x00\x00\x00", "rdp"},
		{"freerdp weston", "\x03\x00\x00\x13\x0e\xd0\x00\x00\x00\x00\x00\x02\x0b\x08\x00\x01\x00\x00\x00", "rdp"},
		{"negotiation failure", "\x03\x00\x00\x13\x0e\xd0\x00\x00\x12\x34\x00\x03\x00\x08\x00\x05\x00\x00\x00", "rdp"},
		{"no rdpNegData", "\x03\x00\x00\x0b\x06\xd0\x00\x00\x12\x34\x00", "rdp"},
		{"siemens s7 cotp cc", "\x03\x00\x00\x16\x11\xd0\x00\x01\x00\x0c\x00\xc0\x01\x0a\xc1\x02\x01\x00\xc2\x02\x01\x02", ""},
		{"x224 disconnect", "\x03\x00\x00\x09\x02\xf0\x80\x21\x80", ""},
		{"truncated", "\x03\x00\x00\x13\x0e\xd0\x00\x00\x12\x34\x00", ""},
		{"http", "HTTP/1.1 400 Bad Request\r\n\r\n", ""},
	}
	for _, tc := range tests {
		if got := h.Verify(tc.data); got != tc.want {
			t.Errorf("%s: Verify = %q, want %q", tc.name, got, tc.want)
		}
	}
}
